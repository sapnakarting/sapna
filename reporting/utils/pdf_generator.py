class FleetEfficiencyPDF(BasePDFReport):
    """PDF generator for fleet efficiency comparison reports."""
    
    def generate(self, efficiency_data: List[Dict], user: str = None) -> bytes:
        """Generate fleet efficiency comparison PDF report."""
        self.add_company_header()
        self.add_title("Fleet Efficiency Comparison Report")
        self.add_metadata(None, None, user)
        
        # Summary data
        avg_efficiency = sum(d['efficiency'] for d in efficiency_data) / len(efficiency_data) if efficiency_data else 0
        best_efficiency = max(efficiency_data, key=lambda x: x['efficiency']) if efficiency_data else None
        
        summary_data = {
            'Average Efficiency': f"{avg_efficiency:.2f} km/l",
            'Best Performer': f"{best_efficiency['truck'].plate_number} ({best_efficiency['efficiency']:.2f} km/l)" if best_efficiency else 'N/A',
            'Fleet Size': str(len(efficiency_data)),
        }
        
        self.add_summary("Summary", summary_data)
        
        # Detailed data table
        if efficiency_data:
            table_headers = ['Truck', 'Efficiency (km/l)', 'Distance', 'Fuel Used', 'Performance vs Average']
            table_data = []
            
            for data in efficiency_data:
                vs_avg = data['efficiency'] - avg_efficiency
                vs_avg_str = f"+{vs_avg:.2f}" if vs_avg > 0 else f"{vs_avg:.2f}"
                
                table_data.append([
                    data['truck'].plate_number,
                    f"{data['efficiency']:.2f}",
                    f"{data['total_distance']:,} km",
                    f"{data['total_fuel']:.2f} liters",
                    vs_avg_str
                ])
            
            self.add_table(table_data, table_headers)
        
        return self.build()


class PredictiveMaintenancePDF(BasePDFReport):
    """PDF generator for predictive maintenance reports."""
    
    def generate(self, maintenance_alerts: List[Dict], user: str = None) -> bytes:
        """Generate predictive maintenance PDF report."""
        self.add_company_header()
        self.add_title("Predictive Maintenance Report")
        self.add_metadata(None, None, user)
        
        # Summary data
        critical_alerts = len([a for a in maintenance_alerts if a['priority'] == 'CRITICAL'])
        warning_alerts = len([a for a in maintenance_alerts if a['priority'] == 'WARNING'])
        info_alerts = len([a for a in maintenance_alerts if a['priority'] == 'INFO'])
        
        summary_data = {
            'Critical Alerts': str(critical_alerts),
            'Warning Alerts': str(warning_alerts),
            'Info Alerts': str(info_alerts),
            'Total Alerts': str(len(maintenance_alerts)),
        }
        
        self.add_summary("Alert Summary", summary_data)
        
        # Detailed alerts table
        if maintenance_alerts:
            table_headers = ['Truck', 'Priority', 'Alert Type', 'Description', 'Recommendation']
            table_data = []
            
            # Sort by priority (Critical first, then Warning, then Info)
            priority_order = {'CRITICAL': 1, 'WARNING': 2, 'INFO': 3}
            sorted_alerts = sorted(maintenance_alerts, key=lambda x: priority_order.get(x['priority'], 4))
            
            for alert in sorted_alerts:
                table_data.append([
                    alert['truck'].plate_number,
                    alert['priority'],
                    alert['alert_type'],
                    alert['description'],
                    alert['recommendation']
                ])
            
            self.add_table(table_data, table_headers)
        
        return self.build()