class DriverPerformancePDF(BasePDFReport):
    """PDF generator for driver performance reports."""
    
    def generate(self, drivers: QuerySet, fuel_logs: QuerySet, date_from: str = None, 
                 date_to: str = None, user: str = None) -> bytes:
        """Generate driver performance PDF report."""
        self.add_company_header()
        self.add_title("Driver Performance Report")
        self.add_metadata(date_from, date_to, user)
        
        # Calculate driver performance metrics
        driver_metrics = []
        for driver in drivers:
            driver_fuel_logs = fuel_logs.filter(driver=driver)
            if driver_fuel_logs.exists():
                total_liters = sum(log.fuel_liters for log in driver_fuel_logs)
                total_cost = sum(log.fuel_cost for log in driver_fuel_logs)
                trips = driver_fuel_logs.count()
                total_distance = sum(
                    log.odometer - log.previous_odometer 
                    for log in driver_fuel_logs 
                    if log.previous_odometer > 0
                )
                avg_efficiency = (total_distance / total_liters) if total_liters > 0 else 0
                
                driver_metrics.append({
                    'driver': driver,
                    'trips': trips,
                    'total_liters': total_liters,
                    'total_cost': total_cost,
                    'total_distance': total_distance,
                    'avg_efficiency': avg_efficiency
                })
        
        # Summary data
        total_trips = sum(m['trips'] for m in driver_metrics)
        total_drivers = len(driver_metrics)
        
        summary_data = {
            'Total Drivers': str(total_drivers),
            'Total Trips': str(total_trips),
            'Average Trips per Driver': f"{total_trips / total_drivers:.1f}" if total_drivers > 0 else "0",
        }
        
        self.add_summary("Summary", summary_data)
        
        # Detailed driver table
        if driver_metrics:
            table_headers = ['Driver Name', 'License No', 'Trips', 'Total Liters', 'Total Cost', 'Total Distance', 'Avg Efficiency']
            table_data = []
            
            for metric in sorted(driver_metrics, key=lambda x: x['avg_efficiency'], reverse=True):
                table_data.append([
                    metric['driver'].name,
                    metric['driver'].license_number,
                    str(metric['trips']),
                    f"{metric['total_liters']:.2f}",
                    self.format_currency(metric['total_cost']),
                    f"{metric['total_distance']:,} km",
                    f"{metric['avg_efficiency']:.2f} km/l"
                ])
            
            self.add_table(table_data, table_headers)
        
        return self.build()


